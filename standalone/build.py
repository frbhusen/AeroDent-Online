"""Builds the AeroDent desktop edition: ``python -m standalone.build [--zip]``.

Produces ``dist/AeroDent/AeroDent.exe`` (a folder that can be zipped or wrapped in an installer).

The installed program contains no readable source code:

* Python: the backend and the launcher are compiled to native machine code with Nuitka (no ``.py``
  or ``.pyc`` files are shipped for them).
* Frontend: the scripts are obfuscated, then packed together with the other web files into one
  scrambled blob that is compiled into the program and served from memory (there is no ``web``
  folder on disk).

Requirements: ``pip install nuitka ordered-set zstandard``, a C compiler (Visual Studio Build Tools
on Windows) and Node.js (``npm install`` is run in standalone/tools for the obfuscator).
No program that has to run on a user's computer can be made impossible to inspect; this removes the
source and makes reverse engineering slow, which is the realistic goal.
"""

import os
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / "standalone" / "tools"
STAGE = ROOT / "build" / "standalone-web"
BLOB_MODULE = ROOT / "standalone" / "_frontend_blob.py"
DIST = ROOT / "dist"
NUITKA_OUT = ROOT / "build" / "nuitka"

# Online-edition-only parts of the frontend that the desktop build leaves out.
EXCLUDED = ("landing page", "trial.html", os.path.join("js", "trial.js"))


def stage_frontend():
    if STAGE.exists():
        shutil.rmtree(STAGE)

    def ignore(directory, names):
        relative = Path(directory).relative_to(ROOT / "web")
        return [name for name in names if os.path.normpath(str(relative / name)) in EXCLUDED]

    shutil.copytree(ROOT / "web", STAGE, ignore=ignore)


def obfuscate_frontend():
    npm = shutil.which("npm") or "npm"
    node = shutil.which("node") or "node"
    if not (TOOLS / "node_modules" / "javascript-obfuscator").exists():
        subprocess.run([npm, "install", "--no-audit", "--no-fund"], check=True, cwd=TOOLS)
    subprocess.run([node, str(TOOLS / "obfuscate.mjs"), str(STAGE)], check=True, cwd=TOOLS)


def write_blob_module():
    """Packs the staged frontend into standalone/_frontend_blob.py (compiled into the program)."""
    from standalone.packed_assets import pack_files

    files = {
        path.relative_to(STAGE).as_posix(): path.read_bytes()
        for path in sorted(STAGE.rglob("*"))
        if path.is_file()
    }
    key = secrets.token_bytes(32)
    BLOB_MODULE.write_text(
        "# Generated by standalone.build - not part of the repository.\n"
        f"KEY = {key!r}\nDATA = {pack_files(files, key)!r}\n",
        encoding="utf-8",
    )
    return len(files)


def compile_program():
    if NUITKA_OUT.exists():  # Nuitka refuses to reuse the leftovers of an interrupted build
        shutil.rmtree(NUITKA_OUT)
    icon = ROOT / "web" / "icons" / "icon.ico"
    command = [
        sys.executable, "-m", "nuitka",
        "--standalone",
        "--assume-yes-for-downloads",
        "--output-dir=" + str(NUITKA_OUT),
        "--output-filename=AeroDent.exe",
        "--windows-console-mode=disable",
        "--company-name=AeroDent",
        "--product-name=AeroDent",
        "--file-version=1.0.0.0",
        "--include-package=backend",
        "--include-package=standalone",
        "--nofollow-import-to=backend.test_*",  # the test scripts are not part of the product
        "--include-module=sqlalchemy.dialects.sqlite",
        "--include-package-data=tzdata",
        "--remove-output",
    ]
    if icon.exists():
        command.append(f"--windows-icon-from-ico={icon}")
    command.append(str(ROOT / "standalone" / "launcher.py"))
    subprocess.run(command, check=True, cwd=ROOT)

    target = DIST / "AeroDent"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(NUITKA_OUT / "launcher.dist", target)
    return target


def main():
    stage_frontend()
    obfuscate_frontend()
    count = write_blob_module()
    print(f"Packed {count} frontend files into {BLOB_MODULE.name}")
    try:
        target = compile_program()
    finally:
        BLOB_MODULE.unlink(missing_ok=True)  # never leave the generated module in the source tree
    print(f"\nBuilt: {target / 'AeroDent.exe'}")
    if "--zip" in sys.argv:
        archive = shutil.make_archive(str(DIST / "AeroDent-windows"), "zip", target)
        print(f"Zipped: {archive}")


if __name__ == "__main__":
    main()
