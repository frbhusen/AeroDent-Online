// Messages that embed a field name or number. Each entry: [regex, builder(match) -> Arabic].
const SERVER_MESSAGE_PATTERNS_AR = [
  [/^Invalid subscription status\. Must be one of .*$/, () => "حالة الاشتراك غير صالحة."],
  [/^Unsupported fields: (.*)$/, (m) => `حقول غير مدعومة: ${m[1]}`],
  [/^Failed to delete clinic: .*$/, () => "تعذر حذف العيادة."],
  [/^(\w+) must be a positive integer\.$/, (m) => `يجب أن يكون ${m[1]} عدداً صحيحاً موجباً.`],
  [/^(\w+) must be a string or null\.$/, (m) => `يجب أن يكون ${m[1]} نصاً أو فارغاً.`],
  [/^(\w+) must be text\.$/, (m) => `يجب أن يكون ${m[1]} نصاً.`],
  [/^(\w+) is too long \(maximum (\d+) characters\)\.$/, (m) => `${m[1]} طويل جداً (الحد الأقصى ${m[2]} حرف).`],
  [/^(\w+) must be at most (\d+) characters\.$/, (m) => `يجب ألا يتجاوز ${m[1]} ${m[2]} حرف.`],
  [/^Invalid (.+)\.$/, (m) => `قيمة غير صالحة: ${m[1]}.`],
  [/^(\w+) must be a valid non-negative amount\.$/, (m) => `يجب أن يكون ${m[1]} مبلغاً صالحاً غير سالب.`],
  [/^(\w+) exceeds maximum allowable amount\.$/, (m) => `${m[1]} يتجاوز الحد الأقصى المسموح.`],
  [/^months must be between 1 and (\d+); page and per_page must be positive integers\.$/, (m) => `يجب أن تكون الأشهر بين 1 و${m[1]}، وأن تكون page وper_page أعداداً صحيحة موجبة.`],
  [/^Medication (\w+) must be a string or null\.$/, (m) => `يجب أن يكون ${m[1]} للدواء نصاً أو فارغاً.`],
  [/^Medication (\w+) is too long \(maximum (\d+) characters\)\.$/, (m) => `${m[1]} للدواء طويل جداً (الحد الأقصى ${m[2]} حرف).`],
  [/^Invalid treatment plan (\w+)\.$/, (m) => `قيمة غير صالحة في الخطة العلاجية: ${m[1]}.`],
];

function translateServerMessage(message) {
  if (typeof message !== "string" || !message) return message;
  if (typeof currentLanguage === "undefined" || currentLanguage !== "ar") return message;
  const exact = SERVER_MESSAGES_AR[message];
  if (exact) return exact;
  for (const [pattern, build] of SERVER_MESSAGE_PATTERNS_AR) {
    const match = message.match(pattern);
    if (match) return build(match);
  }
  return message;
}
